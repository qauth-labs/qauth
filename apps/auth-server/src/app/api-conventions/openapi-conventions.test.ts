/// <reference types="vitest/globals" />
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import swagger from '@fastify/swagger';
import Fastify from 'fastify';
import {
  serializerCompiler,
  validatorCompiler,
  type ZodTypeProvider,
} from 'fastify-type-provider-zod';
import { z } from 'zod';

import {
  type AdminOperation,
  createOperationRegistry,
  defineOperation,
} from '../helpers/admin-operations';
import { openapiOptions } from '../openapi-options';
import { checkApiConventions, type ConventionRule } from './openapi-conventions';
import { pageQuerySchema, pageSchema } from './paging';
import { PROBLEM_SCHEMA_REF, problemResponses } from './problem';

/**
 * The API conventions check (#506), in two parts:
 *
 *   1. over a FIXTURE document: four family operations built with the shared
 *      helpers (`paging.ts`, `problem.ts`) and generated by `@fastify/swagger`
 *      with the server's own `openapiOptions`. It must pass as generated, and
 *      each mutation below must fail exactly the rule it breaks;
 *   2. over the two documents the exporter writes, which CI's stable-surface
 *      drift check keeps equal to what the server generates.
 */

type Doc = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

const REPO_ROOT = join(__dirname, '..', '..', '..', '..', '..');

const realmSchema = z.object({
  id: z.uuid(),
  name: z.string(),
  enabled: z.boolean(),
  createdAt: z.iso.datetime(),
  updatedAt: z.iso.datetime(),
});

const clientSchema = z.object({
  id: z.uuid(),
  client_id: z.string(),
  redirect_uris: z.array(z.string()),
  ownerId: z.uuid(),
  createdAt: z.iso.datetime(),
  lastUsedAt: z.iso.datetime().nullable(),
});

const realmParams = z.object({ realmId: z.uuid() });

/**
 * The fixture's admin operations as a registry defines them (#508). No admin
 * operation is registered on the server yet, so the fixture document is
 * checked against these.
 */
const FIXTURE_OPERATIONS = createOperationRegistry(
  [
    defineOperation({
      id: 'realms.list',
      class: 'read',
      effects: [],
      permissions: ['realms.read'],
      description: 'List the realms.',
    }),
    defineOperation({
      id: 'realms.get',
      class: 'read',
      effects: [],
      permissions: ['realms.read'],
      description: 'Read a realm.',
    }),
    defineOperation({
      id: 'realms.policies.update',
      class: 'security',
      effects: ['credential-path'],
      permissions: ['realms.policies.write', 'realms.policies.security'],
      description: "Change a realm's policies.",
    }),
  ] as AdminOperation[],
  { reserved: [] }
);

/** The check over a fixture document, against the fixture's registry. */
const check = (doc: unknown) => checkApiConventions(doc, { operations: FIXTURE_OPERATIONS });

/** Generate the fixture document through the server's own swagger options. */
async function buildFixtureDocument(): Promise<Doc> {
  const app = Fastify({ logger: false }).withTypeProvider<ZodTypeProvider>();
  app.setValidatorCompiler(validatorCompiler);
  app.setSerializerCompiler(serializerCompiler);
  await app.register(swagger, openapiOptions);

  app.get(
    '/admin/v1-rc.0/realms',
    {
      schema: {
        operationId: 'realms.list',
        security: [{ bearerAuth: [] }],
        'x-qauth-stability': 'stable',
        'x-qauth-class': 'read',
        'x-qauth-permission': 'realms.read',
        querystring: pageQuerySchema,
        response: { 200: pageSchema(realmSchema), ...problemResponses(400, 401, 403) },
      },
    },
    async () => ({ items: [], nextCursor: null })
  );

  app.get(
    '/admin/v1-rc.0/realms/:realmId',
    {
      schema: {
        operationId: 'realms.get',
        security: [{ bearerAuth: [] }],
        'x-qauth-stability': 'stable',
        'x-qauth-class': 'read',
        'x-qauth-permission': 'realms.read',
        params: realmParams,
        response: { 200: realmSchema, ...problemResponses(401, 403, 404) },
      },
    },
    async () => {
      throw new Error('not called');
    }
  );

  app.patch(
    '/admin/v1-rc.0/realms/:realmId/policies',
    {
      schema: {
        operationId: 'realms.policies.update',
        security: [{ bearerAuth: [] }],
        'x-qauth-stability': 'stable',
        'x-qauth-class': 'security',
        'x-qauth-permission': ['realms.policies.write', 'realms.policies.security'],
        'x-qauth-effects': ['credential-path'],
        'x-qauth-two-admin': 'recommended',
        consumes: ['application/merge-patch+json'],
        params: realmParams,
        headers: z.looseObject({ 'if-match': z.string() }),
        body: z.strictObject({
          passwordMinScore: z.int().min(0).max(4).nullable().optional(),
          lockout: z.strictObject({ maxAttempts: z.int().optional() }).optional(),
        }),
        response: {
          200: realmSchema,
          ...problemResponses(400, 401, 403, 404, 412, 422, 428),
        },
      },
    },
    async () => {
      throw new Error('not called');
    }
  );

  app.get(
    '/developer/v1-rc.0/clients',
    {
      schema: {
        operationId: 'clients.list',
        security: [{ bearerAuth: [] }],
        'x-qauth-stability': 'experimental',
        'x-qauth-class': 'read',
        'x-qauth-permission': 'clients.read',
        querystring: pageQuerySchema,
        response: { 200: pageSchema(clientSchema), ...problemResponses(400, 401) },
      },
    },
    async () => ({ items: [], nextCursor: null })
  );

  // Outside the families: snake_case, no operationId, no extensions. Not checked.
  app.get(
    '/oauth/example',
    {
      schema: {
        response: { 200: z.object({ access_token: z.string(), not_registered: z.string() }) },
      },
    },
    async () => ({ access_token: 'a', not_registered: 'b' })
  );

  await app.ready();
  const document = structuredClone(app.swagger()) as Doc;
  await app.close();
  return document;
}

let fixture: Doc;

beforeAll(async () => {
  fixture = await buildFixtureDocument();
});

/** A deep copy of the fixture with `mutate` applied. */
function mutated(mutate: (doc: Doc) => void): Doc {
  const copy = structuredClone(fixture);
  mutate(copy);
  return copy;
}

function rulesOf(doc: Doc): ConventionRule[] {
  return [...new Set(check(doc).violations.map((violation) => violation.rule))];
}

const LIST = (doc: Doc) => doc.paths['/admin/v1-rc.0/realms'].get;
const GET = (doc: Doc) => doc.paths['/admin/v1-rc.0/realms/{realmId}'].get;
const PATCH = (doc: Doc) => doc.paths['/admin/v1-rc.0/realms/{realmId}/policies'].patch;
const CLIENTS = (doc: Doc) => doc.paths['/developer/v1-rc.0/clients'].get;
const jsonSchema = (operation: Doc, status = '200') =>
  operation.responses[status].content['application/json'].schema;

describe('the API conventions check — fixture document (#506)', () => {
  it('passes the fixture as the shared helpers and openapiOptions generate it', () => {
    const report = check(fixture);
    expect(report.violations).toEqual([]);
    expect(report.checkedOperations).toBe(4);
  });

  it('generates the shapes the rules read: a $ref to the Problem component, the paging parameters, the merge-patch body', () => {
    expect(GET(fixture).responses['404'].content).toEqual({
      'application/problem+json': { schema: { $ref: PROBLEM_SCHEMA_REF } },
    });
    expect(fixture.components.schemas.Problem.properties.trace_id).toEqual({ type: 'string' });
    expect(fixture.components.schemas.Problem.properties.code['x-extensible-enum']).toContain(
      'validation_error'
    );
    // `openapiOptions` publishes only referenced components: no `ProblemInput`.
    expect(Object.keys(fixture.components.schemas)).toEqual(['Problem']);

    const limit = LIST(fixture).parameters.find((p: Doc) => p.name === 'limit');
    expect(limit.schema).toMatchObject({ type: 'integer', minimum: 1, maximum: 200, default: 50 });
    expect(Object.keys(PATCH(fixture).requestBody.content)).toEqual([
      'application/merge-patch+json',
    ]);
    expect(PATCH(fixture).parameters).toContainEqual(
      expect.objectContaining({ in: 'header', name: 'if-match', required: true })
    );
  });

  it('ignores operations outside the API families', () => {
    const doc = mutated((d) => {
      d.paths['/api/clients'] = { get: { responses: { 200: { description: 'x' } } } };
    });
    expect(check(doc).violations).toEqual([]);
  });

  describe('fails when an operation lacks a required element', () => {
    it.each([
      ['operationId', 'operation-id'],
      ['security', 'security'],
      ['x-qauth-class', 'class'],
      ['x-qauth-permission', 'permission'],
      ['x-qauth-stability', 'stability'],
    ] as const)('MUTATION: no %s → %s', (key, rule) => {
      const doc = mutated((d) => {
        delete GET(d)[key];
      });
      expect(rulesOf(doc)).toEqual([rule]);
    });

    it('MUTATION: an operationId that is not <resource>.<verb>', () => {
      expect(rulesOf(mutated((d) => (GET(d).operationId = 'getRealm')))).toEqual(['operation-id']);
    });

    it('MUTATION: two operations with one operationId', () => {
      expect(rulesOf(mutated((d) => (GET(d).operationId = 'realms.list')))).toEqual([
        'operation-id',
      ]);
    });

    it('MUTATION: an empty security requirement lets an anonymous caller in', () => {
      expect(rulesOf(mutated((d) => (GET(d).security = [{}])))).toEqual(['security']);
    });

    it('MUTATION: a security scheme the document does not define', () => {
      expect(rulesOf(mutated((d) => (GET(d).security = [{ mtls: [] }])))).toEqual(['security']);
    });

    it('MUTATION: an unknown class, and a security class outside the admin API', () => {
      expect(rulesOf(mutated((d) => (GET(d)['x-qauth-class'] = 'admin')))).toEqual(['class']);
      expect(
        rulesOf(
          mutated((d) => {
            Object.assign(CLIENTS(d), {
              'x-qauth-class': 'security',
              'x-qauth-effects': ['token-content'],
              'x-qauth-two-admin': 'recommended',
            });
          })
        )
      ).toEqual(['class']);
    });

    it('MUTATION: a permission that is not a permission id', () => {
      expect(rulesOf(mutated((d) => (GET(d)['x-qauth-permission'] = 'qauth:admin:read')))).toEqual([
        'permission',
      ]);
      expect(rulesOf(mutated((d) => (GET(d)['x-qauth-permission'] = [])))).toEqual(['permission']);
    });

    // #507: an admin operation names permissions of the admin catalog.
    it('MUTATION: an admin permission the catalog does not have', () => {
      expect(rulesOf(mutated((d) => (GET(d)['x-qauth-permission'] = 'realms.delete')))).toEqual([
        'permission',
      ]);
      expect(
        rulesOf(
          mutated(
            (d) =>
              (PATCH(d)['x-qauth-permission'] = ['realms.policies.write', 'realms.policies.admin'])
          )
        )
      ).toEqual(['permission']);
    });

    // #507: the class of an admin operation is the strictest class of its permissions.
    it('MUTATION: an admin class that is not the strictest class of its permissions', () => {
      // A security operation that names only a write permission.
      expect(
        rulesOf(mutated((d) => (PATCH(d)['x-qauth-permission'] = 'realms.policies.write')))
      ).toEqual(['permission']);
      // A read operation that names a write permission.
      expect(
        rulesOf(
          mutated((d) => (GET(d)['x-qauth-permission'] = ['realms.read', 'realms.policies.write']))
        )
      ).toEqual(['permission']);
      // A write operation that names a security permission: also missing its
      // effects and two-admin marker would be reported by their own rules.
      expect(
        rulesOf(
          mutated((d) => {
            Object.assign(PATCH(d), { 'x-qauth-class': 'write' });
            delete PATCH(d)['x-qauth-effects'];
            delete PATCH(d)['x-qauth-two-admin'];
          })
        )
      ).toEqual(['permission']);
    });

    it('MUTATION: a security operation without effects, or without the two-admin marker', () => {
      expect(rulesOf(mutated((d) => delete PATCH(d)['x-qauth-effects']))).toEqual(['effects']);
      expect(rulesOf(mutated((d) => delete PATCH(d)['x-qauth-two-admin']))).toEqual(['two-admin']);
    });

    // #508: the effect tags are a closed list.
    it('MUTATION: an effect tag outside the closed list', () => {
      expect(rulesOf(mutated((d) => (PATCH(d)['x-qauth-effects'] = ['credential-paths'])))).toEqual(
        ['effects']
      );
    });

    it('MUTATION: effects or the two-admin marker on an operation that is not security', () => {
      expect(rulesOf(mutated((d) => (GET(d)['x-qauth-effects'] = ['import'])))).toEqual([
        'effects',
      ]);
      expect(rulesOf(mutated((d) => (GET(d)['x-qauth-two-admin'] = 'recommended')))).toEqual([
        'two-admin',
      ]);
    });
  });

  // #508: an admin operation of the document is the registry's operation.
  describe('fails when an admin operation disagrees with the operation registry', () => {
    const registryMessages = (doc: Doc) =>
      check(doc)
        .violations.filter((violation) => violation.rule === 'registry')
        .map((violation) => violation.message);

    // Acceptance criterion: the invariant test fails when x-qauth-class
    // disagrees with the registry. The document stays well formed (a write
    // class with a write permission), so only the registry rule speaks.
    it('MUTATION: an x-qauth-class the registry does not give the operation', () => {
      const doc = mutated((d) => {
        GET(d)['x-qauth-class'] = 'write';
        GET(d)['x-qauth-permission'] = 'realms.policies.write';
      });
      expect(rulesOf(doc)).toEqual(['registry']);
      expect(registryMessages(doc)).toEqual([
        'x-qauth-class is write, but the registry gives realms.get the class read',
        'x-qauth-permission is realms.policies.write, but the registry gives realms.get realms.read',
      ]);
    });

    it('MUTATION: the registry gives the operation another class than the document', () => {
      const registry = createOperationRegistry(
        FIXTURE_OPERATIONS.all.map((operation) =>
          operation.id === 'realms.get'
            ? defineOperation({
                ...operation,
                class: 'write',
                permissions: ['realms.policies.write'],
              })
            : operation
        ) as AdminOperation[],
        { reserved: [] }
      );
      const { violations } = checkApiConventions(fixture, { operations: registry });
      expect(violations.map((violation) => [violation.operation, violation.rule])).toEqual([
        ['GET /admin/v1-rc.0/realms/{realmId}', 'registry'],
        ['GET /admin/v1-rc.0/realms/{realmId}', 'registry'],
      ]);
      expect(violations[0].message).toBe(
        'x-qauth-class is read, but the registry gives realms.get the class write'
      );
    });

    it('MUTATION: an x-qauth-permission the registry does not give the operation', () => {
      const doc = mutated((d) => (GET(d)['x-qauth-permission'] = ['realms.read', 'realms.export']));
      expect(rulesOf(doc)).toEqual(['registry']);
      // The same permissions in another order agree.
      expect(
        rulesOf(
          mutated(
            (d) =>
              (PATCH(d)['x-qauth-permission'] = [
                'realms.policies.security',
                'realms.policies.write',
              ])
          )
        )
      ).toEqual([]);
    });

    it('MUTATION: x-qauth-effects the registry does not give the operation', () => {
      const doc = mutated(
        (d) => (PATCH(d)['x-qauth-effects'] = ['credential-path', 'posture-loosening'])
      );
      expect(rulesOf(doc)).toEqual(['registry']);
      expect(registryMessages(doc)).toEqual([
        'x-qauth-effects is credential-path, posture-loosening, but the registry gives realms.policies.update credential-path',
      ]);
    });

    it('MUTATION: an admin operation the registry does not hold', () => {
      const doc = mutated((d) => (GET(d).operationId = 'realms.read'));
      expect(rulesOf(doc)).toEqual(['registry']);
      expect(registryMessages(doc)[0]).toContain(
        '"realms.read" is not in the admin operation registry'
      );
    });

    it('reports a malformed member once, by its own rule', () => {
      expect(rulesOf(mutated((d) => (GET(d)['x-qauth-class'] = 'admin')))).toEqual(['class']);
      expect(rulesOf(mutated((d) => (GET(d).operationId = 'getRealm')))).toEqual(['operation-id']);
    });

    it("compares with the server's own registry by default, which holds no operation yet", () => {
      const { violations } = checkApiConventions(fixture);
      expect(violations.map((violation) => [violation.operation, violation.rule])).toEqual([
        ['GET /admin/v1-rc.0/realms', 'registry'],
        ['GET /admin/v1-rc.0/realms/{realmId}', 'registry'],
        ['PATCH /admin/v1-rc.0/realms/{realmId}/policies', 'registry'],
      ]);
    });

    it('leaves the account and developer families to their own rules', () => {
      expect(rulesOf(mutated((d) => (CLIENTS(d).operationId = 'clients.search')))).toEqual([]);
    });
  });

  describe('fails when a name is not camelCase and not on the OAuth metadata allow list', () => {
    it('MUTATION: a snake_case response member', () => {
      const doc = mutated((d) => {
        const realm = jsonSchema(GET(d));
        realm.properties.display_name = { type: 'string' };
      });
      const { violations } = check(doc);
      expect(violations.map((v) => v.rule)).toEqual(['naming']);
      expect(violations[0].message).toContain('"display_name"');
    });

    it('MUTATION: a snake_case member nested in a list item and in a request body', () => {
      const doc = mutated((d) => {
        jsonSchema(LIST(d)).properties.items.items.properties.Name = { type: 'string' };
        const body = PATCH(d).requestBody.content['application/merge-patch+json'].schema;
        body.properties.lockout.properties.max_attempts = { type: 'integer' };
      });
      expect(check(doc).violations.map((v) => v.rule)).toEqual(['naming', 'naming']);
    });

    it('MUTATION: a snake_case query parameter', () => {
      const doc = mutated((d) => {
        LIST(d).parameters.push({ in: 'query', name: 'page_token', schema: { type: 'string' } });
      });
      expect(rulesOf(doc)).toEqual(['naming']);
    });

    it('passes registered OAuth names (redirect_uris, client_id) and trace_id', () => {
      const item = jsonSchema(CLIENTS(fixture)).properties.items.items;
      expect(Object.keys(item.properties)).toEqual(
        expect.arrayContaining(['client_id', 'redirect_uris'])
      );
      expect(rulesOf(fixture)).toEqual([]);
    });
  });

  describe('fails when an error response does not reference the shared problem schema', () => {
    it('MUTATION: an inline schema instead of the reference', () => {
      const doc = mutated((d) => {
        GET(d).responses['404'].content['application/problem+json'].schema = {
          type: 'object',
          properties: { error: { type: 'string' } },
        };
      });
      expect(rulesOf(doc)).toEqual(['problem']);
    });

    it('MUTATION: an error response sent as application/json', () => {
      const doc = mutated((d) => {
        GET(d).responses['403'].content = {
          'application/json': { schema: { $ref: PROBLEM_SCHEMA_REF } },
        };
      });
      expect(rulesOf(doc)).toEqual(['problem']);
    });

    it('MUTATION: a default response with no problem content', () => {
      const doc = mutated((d) => {
        GET(d).responses.default = { description: 'Error' };
      });
      expect(rulesOf(doc)).toEqual(['problem']);
    });

    it('MUTATION: the reference resolves to nothing', () => {
      expect(rulesOf(mutated((d) => delete d.components.schemas.Problem))).toEqual(['problem']);
    });
  });

  describe('the other rules', () => {
    it('MUTATION: a family path without its major version', () => {
      const doc = mutated((d) => {
        d.paths['/admin/realms'] = d.paths['/admin/v1-rc.0/realms'];
        delete d.paths['/admin/v1-rc.0/realms'];
        d.paths['/admin/realms'].get.operationId = 'realms.list';
      });
      expect(rulesOf(doc)).toEqual(['path-version']);
    });

    it('MUTATION: an id that is not a UUID string, and a time that is an epoch number', () => {
      const doc = mutated((d) => {
        jsonSchema(GET(d)).properties.id = { type: 'integer' };
        jsonSchema(GET(d)).properties.createdAt = { type: 'integer' };
      });
      expect(rulesOf(doc)).toEqual(['id-format', 'time-format']);
    });

    it('MUTATION: a request object that accepts unknown members', () => {
      const doc = mutated((d) => {
        const body = PATCH(d).requestBody.content['application/merge-patch+json'].schema;
        delete body.properties.lockout.additionalProperties;
      });
      expect(rulesOf(doc)).toEqual(['unknown-fields']);
    });

    it('MUTATION: a list answered as a bare array', () => {
      const doc = mutated((d) => {
        LIST(d).responses['200'].content['application/json'].schema = {
          type: 'array',
          items: { type: 'object' },
        };
      });
      expect(rulesOf(doc)).toEqual(['paging']);
    });

    it('MUTATION: a list without nextCursor, or with a member beside items', () => {
      expect(rulesOf(mutated((d) => delete jsonSchema(LIST(d)).properties.nextCursor))).toEqual([
        'paging',
      ]);
      // nextCursor is null on the last page, so a plain string cannot describe it
      expect(
        rulesOf(mutated((d) => (jsonSchema(LIST(d)).properties.nextCursor = { type: 'string' })))
      ).toEqual(['paging']);
      expect(
        rulesOf(mutated((d) => (jsonSchema(LIST(d)).properties.total = { type: 'integer' })))
      ).toEqual(['paging']);
    });

    it('MUTATION: a limit above 200, a missing cursor, an offset parameter', () => {
      const limitOf = (d: Doc) => LIST(d).parameters.find((p: Doc) => p.name === 'limit');
      expect(rulesOf(mutated((d) => (limitOf(d).schema.maximum = 1000)))).toEqual(['paging']);
      expect(rulesOf(mutated((d) => (limitOf(d).schema.default = 20)))).toEqual(['paging']);
      expect(
        rulesOf(
          mutated((d) => {
            LIST(d).parameters = LIST(d).parameters.filter((p: Doc) => p.name !== 'cursor');
          })
        )
      ).toEqual(['paging']);
      expect(
        rulesOf(
          mutated((d) => {
            LIST(d).parameters.push({ in: 'query', name: 'offset', schema: { type: 'integer' } });
          })
        )
      ).toEqual(['paging']);
    });

    it('MUTATION: a PATCH body that is not a JSON Merge Patch', () => {
      const doc = mutated((d) => {
        const content = PATCH(d).requestBody.content;
        content['application/json'] = content['application/merge-patch+json'];
        delete content['application/merge-patch+json'];
      });
      expect(rulesOf(doc)).toEqual(['merge-patch']);
    });

    it('MUTATION: an update without If-Match, or without its 412 and 428 answers', () => {
      expect(
        rulesOf(
          mutated((d) => {
            PATCH(d).parameters = PATCH(d).parameters.filter((p: Doc) => p.in !== 'header');
          })
        )
      ).toEqual(['if-match']);
      const { violations } = check(
        mutated((d) => {
          delete PATCH(d).responses['412'];
          delete PATCH(d).responses['428'];
        })
      );
      expect(violations.map((v) => v.rule)).toEqual(['if-match', 'if-match']);
    });
  });
});

describe('the API conventions check — the generated documents (#506)', () => {
  it.each(['stable-surface/openapi.json', 'apps/docs-site/public/openapi.json'])(
    '%s follows the conventions',
    (path) => {
      const document = JSON.parse(readFileSync(join(REPO_ROOT, path), 'utf8')) as unknown;
      const report = checkApiConventions(document);
      expect(report.violations).toEqual([]);
    }
  );
});
