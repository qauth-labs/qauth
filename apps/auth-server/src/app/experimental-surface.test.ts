import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

import { EXPERIMENTAL_ITEMS } from '@qauth-labs/shared-stability';
import { beforeAll, describe, expect, it } from 'vitest';

/**
 * The wire suite may import no workspace project (`apps/wire-suite/README.md`),
 * so what it checks a default deployment hides (ADR-018 §5, #477) reaches it
 * as a generated module: every operation the maximal OpenAPI export tags
 * `x-qauth-stability: experimental`, and every discovery member an item of
 * the experimental-feature registry adds.
 *
 * This test is the generator: `pnpm nx test auth-server -- -u` rewrites the
 * module, and without `-u` the test fails until the committed module matches.
 * It reads the committed maximal export, which the stable-surface check keeps
 * in step with the code. The module goes through Oxfmt first, so the
 * committed file is already formatted.
 */

const REPO_ROOT = join(__dirname, '..', '..', '..', '..');

/** The generated module, from the repository root. */
const FIXTURE_PATH = 'apps/wire-suite/src/fixtures/experimental.ts';

/** The maximal OpenAPI export: every switch that registers a route turned on. */
const MAXIMAL_EXPORT_PATH = 'apps/docs-site/public/openapi.json';

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

/** Oxfmt's command line, which formats with the repository's `.oxfmtrc.json`. */
const OXFMT = join(
  dirname(createRequire(__filename).resolve('oxfmt/package.json')),
  'bin',
  'oxfmt'
);

interface OpenApiDocument {
  readonly paths?: Readonly<Record<string, Readonly<Record<string, unknown>>>>;
}

/** Every operation `document` tags experimental, as `METHOD /path`, ordered by path. */
function experimentalOperations(document: OpenApiDocument): string[] {
  const operations: string[] = [];
  for (const path of Object.keys(document.paths ?? {}).sort()) {
    const item = document.paths?.[path] ?? {};
    for (const method of HTTP_METHODS) {
      const operation = item[method] as Record<string, unknown> | undefined;
      if (operation?.['x-qauth-stability'] === 'experimental') {
        operations.push(`${method.toUpperCase()} ${path}`);
      }
    }
  }
  return operations;
}

/** The module, unformatted. */
function renderFixture(operations: readonly string[], members: readonly string[]): string {
  return `/**
 * What a default deployment must not serve or advertise (ADR-018 §5): the
 * experimental operations and the discovery members of experimental items.
 *
 * Generated by \`apps/auth-server/src/app/experimental-surface.test.ts\` from
 * the maximal OpenAPI export (\`${MAXIMAL_EXPORT_PATH}\`) and the
 * experimental-feature registry (\`libs/shared/stability\`). Do not edit by
 * hand: run \`pnpm nx test auth-server -- -u\`.
 */

/** Every operation the maximal export tags \`x-qauth-stability: experimental\`, as \`METHOD /path\`. */
export const EXPERIMENTAL_OPERATIONS: readonly string[] = ${JSON.stringify(operations)};

/** Every discovery member an experimental item adds while its switch is on. */
export const EXPERIMENTAL_DISCOVERY_MEMBERS: readonly string[] = ${JSON.stringify(members)};
`;
}

/** `text` as Oxfmt formats the file at `path`. */
function formatAs(path: string, text: string): string {
  return execFileSync(process.execPath, [OXFMT, `--stdin-filepath=${path}`], {
    cwd: REPO_ROOT,
    input: text,
    encoding: 'utf8',
  });
}

let operations: string[] = [];
let members: string[] = [];
let fixture = '';
beforeAll(() => {
  const maximal = JSON.parse(
    readFileSync(join(REPO_ROOT, MAXIMAL_EXPORT_PATH), 'utf8')
  ) as OpenApiDocument;
  operations = experimentalOperations(maximal);
  members = EXPERIMENTAL_ITEMS.flatMap((item) => item.discoveryMembers);
  fixture = formatAs(join(REPO_ROOT, FIXTURE_PATH), renderFixture(operations, members));
});

describe("the wire suite's list of what a default deployment hides", () => {
  it('is what the maximal export and the registry give (regenerate with `pnpm nx test auth-server -- -u`)', async () => {
    await expect(fixture).toMatchFileSnapshot(join(REPO_ROOT, FIXTURE_PATH));
  });

  it('lists the experimental operations of the maximal export', () => {
    expect(operations).toContain('POST /oid4vp/response');
  });

  it('lists the discovery members of every registry item', () => {
    for (const item of EXPERIMENTAL_ITEMS) {
      for (const member of item.discoveryMembers) expect(fixture).toContain(`'${member}'`);
    }
    expect(members.length).toBeGreaterThan(0);
  });
});
