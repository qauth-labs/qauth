import { REALM_POLICY_REGISTRY } from '@qauth-labs/server-realm-policy';
import type { z } from 'zod';

import { REALM_FILE_FORMAT } from './format';
import { REALM_FILE_SECTIONS } from './sections';

/**
 * What is wrong with a realm file, member by member (#515): every issue has
 * the path to the member at fault, so a refusal names it. A member the format
 * does not know is one issue of its own, and the message says why it is not
 * in a file when the reason is the format's: a secret value, a client a
 * developer owns or that registered itself, an id the server generates, or a
 * section of a later release.
 */

/** One problem of a realm file. */
export interface RealmFileIssue {
  /** The path to the member at fault, from the file's root. */
  readonly path: readonly (string | number)[];
  /** The same path as a JSON Pointer (RFC 6901): `/clients/0/client_secret`. */
  readonly pointer: string;
  readonly message: string;
}

/** A JSON Pointer (RFC 6901) of `path`; the root is the empty string. */
export function jsonPointer(path: readonly (string | number)[]): string {
  return path.map((token) => `/${String(token).replace(/~/g, '~0').replace(/\//g, '~1')}`).join('');
}

const dotted = (path: readonly (string | number)[]): string => path.join('.');

/** The sections whose entries are clients, which a client's own members describe. */
const CLIENT_SECTIONS = new Set(['clients', 'cimd_clients', 'system_client']);

/**
 * Members of a client that a server's registration or storage knows and a
 * realm file never holds, by why. Any other unknown member is refused as
 * well; these only get the reason.
 */
const CLIENT_MEMBERS_NEVER_IN_A_FILE: Readonly<Record<string, string>> = Object.freeze({
  // RFC 7591 §3.2.1: the values a registration response returns as secrets.
  client_secret: 'secret',
  registration_access_token: 'secret',
  // Operator-managed clients only: a developer's client and a dynamically
  // registered one are outside the file.
  developer_id: 'not-operator-managed',
  dynamic_registered_at: 'not-operator-managed',
  // Matched by client_id, never by a row's id or its timestamps.
  id: 'generated',
  created_at: 'generated',
  updated_at: 'generated',
});

function unknownSection(key: string): string {
  const sections = ['format', 'realm', ...REALM_FILE_SECTIONS.map(({ name }) => name)].join(', ');
  return `"${key}" is not a section of a realm file of format ${REALM_FILE_FORMAT}, which has ${sections}: a section a later release adds is refused, never skipped, so import such a file with that release, or correct the name`;
}

function unknownPolicyMember(parent: readonly (string | number)[], key: string): string {
  const fieldPath = dotted([...parent.slice(1), key]);
  if (REALM_POLICY_REGISTRY.field(fieldPath)?.field.secret) {
    return `policies.${fieldPath} is a secret: a realm file never holds a secret value, so set it on the target realm itself; an import lists the secrets the realm still needs (secretsToSet)`;
  }
  if (key.endsWith('Set') && key.length > 'Set'.length) {
    const secretPath = fieldPath.slice(0, -'Set'.length);
    if (REALM_POLICY_REGISTRY.field(secretPath)?.field.secret) {
      return `policies.${fieldPath} is the realm representation's flag for the secret policies.${secretPath}: a realm file leaves the flag out with the secret, and an import lists the secrets the realm still needs (secretsToSet)`;
    }
  }
  if (parent.length === 1) {
    const groups = REALM_POLICY_REGISTRY.groups().join(', ');
    return `"${key}" is not a policy group of this server's realm policy schema (${REALM_POLICY_REGISTRY.version}), which has ${groups}: a group a later release adds is refused, never skipped`;
  }
  return `"${key}" is not a field of ${dotted(parent)}`;
}

function unknownClientMember(parent: readonly (string | number)[], key: string): string {
  const where = dotted([...parent, key]);
  switch (CLIENT_MEMBERS_NEVER_IN_A_FILE[key]) {
    case 'secret':
      return `${where} is a secret: a realm file never holds a secret value, and a client's secret is set on the target realm, never copied (secretsToSet)`;
    case 'not-operator-managed':
      return `${where} marks a developer-owned or dynamically registered client, which is outside a realm file: it describes operator-managed clients only`;
    case 'generated':
      return `${where} is generated by the server, and a realm file holds no such value: a client is matched by its client_id`;
    default:
      return `"${key}" is not a field of a ${String(parent[0])} entry`;
  }
}

/** Why the member `key` of the object at `parent` is not in a realm file. */
function unknownMember(parent: readonly (string | number)[], key: string): string {
  if (parent.length === 0) return unknownSection(key);
  if (parent[0] === 'policies') return unknownPolicyMember(parent, key);
  const entryDepth = parent[0] === 'system_client' ? 1 : 2;
  if (CLIENT_SECTIONS.has(String(parent[0])) && parent.length === entryDepth) {
    return unknownClientMember(parent, key);
  }
  return `"${key}" is not a field of ${dotted(parent)}`;
}

const pathOf = (path: readonly PropertyKey[]): (string | number)[] =>
  path.map((token) => (typeof token === 'number' ? token : String(token)));

/** The issues of a realm file that `error` refused, in the order Zod found them. */
export function realmFileIssues(error: z.ZodError): RealmFileIssue[] {
  const issues: RealmFileIssue[] = [];
  for (const issue of error.issues) {
    const path = pathOf(issue.path);
    if (issue.code === 'unrecognized_keys') {
      for (const key of issue.keys) {
        const memberPath = [...path, key];
        issues.push({
          path: memberPath,
          pointer: jsonPointer(memberPath),
          message: unknownMember(path, key),
        });
      }
      continue;
    }
    issues.push({ path, pointer: jsonPointer(path), message: issue.message });
  }
  return issues;
}
