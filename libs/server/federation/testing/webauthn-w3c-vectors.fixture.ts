/** Hex to base64url, the encoding of the browser's JSON responses. */
export function hexToBase64Url(hex: string): string {
  return Buffer.from(hex, 'hex').toString('base64url');
}

/**
 * The vector's registration as `PublicKeyCredential.toJSON()` would return it
 * (WebAuthn Level 3 §5.1 `RegistrationResponseJSON`).
 */
export function w3cRegistrationResponse(vector: W3cWebAuthnVector) {
  const id = hexToBase64Url(vector.credentialId);
  return {
    id,
    rawId: id,
    type: 'public-key',
    response: {
      clientDataJSON: hexToBase64Url(vector.registration.clientDataJSON),
      attestationObject: hexToBase64Url(vector.registration.attestationObject),
      transports: ['internal'],
    },
    clientExtensionResults: {},
  };
}

/**
 * The vector's assertion as `PublicKeyCredential.toJSON()` would return it
 * (WebAuthn Level 3 §5.1 `AuthenticationResponseJSON`). The vectors print no
 * user handle, so the response carries none.
 */
export function w3cAuthenticationResponse(vector: W3cWebAuthnVector) {
  const id = hexToBase64Url(vector.credentialId);
  return {
    id,
    rawId: id,
    type: 'public-key',
    response: {
      clientDataJSON: hexToBase64Url(vector.authentication.clientDataJSON),
      authenticatorData: hexToBase64Url(vector.authentication.authenticatorData),
      signature: hexToBase64Url(vector.authentication.signature),
    },
    clientExtensionResults: {},
  };
}
