import { ACCOUNT_API_AUDIENCE, ACCOUNT_API_PREFIX, CONTRACT_SITE_PATH } from './identifiers';
import { NOTICES } from './notices';
import { ACCOUNT_OPERATIONS, ACCOUNT_TAGS, type AccountOperation } from './operations';
import {
  ACCOUNT_PROBLEM_CODES,
  ADDED_PROBLEM_CODES,
  FIELD_ERROR_REASONS,
  PASSWORD_REJECTION_REASONS,
} from './problems';
import {
  ACT_CHAIN_RULES_TEXT,
  API_RULES,
  FRESH_AUTHENTICATION_RULES_TEXT,
  STATUS_RULES,
  TOKEN_RULES,
  VERSIONING_RULES,
} from './rules';
import { SECURITY_LOG_KINDS, type SecurityLogSource } from './security-log';

/**
 * The docs page `reference/account-api.md`, rendered from the contract (#588).
 * The export script writes it and runs it through Oxfmt; a test compares the
 * committed page with this output, so the page and the published document
 * cannot disagree.
 */

/** The date the page's prose was last checked; change it with the prose. */
export const ACCOUNT_PAGE_LAST_VERIFIED = '2026-11-02';

const bullets = (lines: readonly string[]) => lines.map((line) => `- ${line}`).join('\n');

const code = (value: string) => `\`${value}\``;

const FRESH = {
  none: '—',
  'strongest-factor': 'Strongest factor',
  'strongest-factor-or-recovery-code': 'Strongest factor or recovery code',
} as const;

function operationRow(operation: AccountOperation): string {
  return `| ${operation.summary} (${code(operation.id)}) | ${code(
    `${operation.method.toUpperCase()} ${operation.path}`
  )} | ${FRESH[operation.freshAuthentication]} | ${
    operation.actChain === 'refused' ? 'Refused' : 'Accepted'
  } | ${operation.success.status} | ${
    (operation.codes ?? []).length === 0 ? '—' : (operation.codes ?? []).map(code).join(', ')
  } |`;
}

function operationTables(): string {
  return Object.entries(ACCOUNT_TAGS)
    .map(([tag, description]) => {
      const rows = ACCOUNT_OPERATIONS.filter((operation) => operation.tag === tag).map(
        operationRow
      );
      return `### ${tag}

${description}

| Operation | Request | Fresh authentication | Act-chain token | Success | Its own codes |
| --------- | ------- | -------------------- | --------------- | ------- | ------------- |
${rows.join('\n')}`;
    })
    .join('\n\n');
}

const source = (entry: SecurityLogSource) =>
  `${code(entry.event)}${entry.status === 'planned' ? ` (with #${entry.issue})` : ''}${
    entry.only === undefined ? '' : `, only ${entry.only}`
  }`;

function securityLogRows(): string[] {
  return Object.entries(SECURITY_LOG_KINDS).map(
    ([kind, entry]) =>
      `| ${code(kind)} | ${entry.description} | ${entry.sources.map(source).join(', ')} | ${
        entry.reportable ? 'Yes' : 'No'
      } |`
  );
}

function noticeRows(): string[] {
  return Object.entries(NOTICES).map(
    ([name, notice]) =>
      `| ${code(name)} | ${notice.description} | ${notice.mandatory ? 'Yes' : 'No'} |`
  );
}

function problemRows(): string[] {
  return Object.entries(ACCOUNT_PROBLEM_CODES).map(
    ([name, entry]) => `| ${code(name)} | ${entry.status} | ${entry.description} |`
  );
}

