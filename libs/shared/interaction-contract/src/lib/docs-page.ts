/**
 * The docs page `reference/interaction-api.md`, rendered from the contract
 * (#590). The export script writes it and runs it through Oxfmt; a test
 * compares the committed page with this output, so the page and the published
 * document cannot disagree.
 */

/** The date the page's prose was last checked; change it with the prose. */
export const INTERACTION_PAGE_LAST_VERIFIED = '2026-10-26';

/** Where the docs site serves the contract's files. */
export const CONTRACT_SITE_PATH = `/interaction/${INTERACTION_API_VERSION}/`;

const bullets = (lines: readonly string[]) => lines.map((line) => `- ${line}`).join('\n');

const code = (value: string) => `\`${value}\``;

type Operation = {
  operationId: string;
  summary: string;
  'x-qauth-flow-cookie': string;
  'x-qauth-csrf': string;
  responses: Record<string, unknown>;
};

function operationRows(document: OpenApiDocument): string[] {
  const rows: string[] = [];
  const paths = document['paths'] as Record<string, Record<string, Operation>>;
  for (const [path, item] of Object.entries(paths)) {
    for (const [method, operation] of Object.entries(item)) {
      const statuses = Object.keys(operation.responses);
      const success = statuses.filter((status) => status.startsWith('2') || status.startsWith('3'));
      const errors = statuses.filter((status) => status.startsWith('4') || status.startsWith('5'));
      rows.push(
        `| ${operation.summary} | ${code(`${method.toUpperCase()} ${path}`)} | ${
          operation['x-qauth-flow-cookie'] === 'required' ? 'Yes' : 'No'
        } | ${operation['x-qauth-csrf'] === 'required' ? 'Yes' : 'No'} | ${success.join(', ')} | ${errors.join(', ')} |`
      );
    }
  }
  return rows;
}

const fieldList = (schema: unknown): string => {
  const properties = Object.keys(
    ((schema as { properties?: Record<string, unknown> }).properties ?? {}) as object
  );
  return properties.length === 0 ? '—' : properties.map(code).join(', ');
};

function stepRow(step: StepDefinition): string {
  return `| [${code(step.name)}](#${step.name}) | ${
    step.transports.includes('fipa') ? 'Both' : 'Interaction API'
  } | ${fieldList(step.answer)} | ${step.errors.length === 0 ? '—' : step.errors.map(code).join(', ')} | ${
    step.amr.length === 0 ? '—' : step.amr.map(code).join(', ')
  } | ${fieldList(step.personal)} |`;
}

function stepSection(step: StepDefinition): string {
  return [
    `### ${step.name}`,
    `${code(step.urn)} — ${step.summary}`,
    step.description,
    `- Params: ${fieldList(step.params)}`,
    `- Schema: [${stepSchemaFile(step)}](${CONTRACT_SITE_PATH}${stepSchemaFile(step)})`,
  ].join('\n\n');
}

function problemRows(): string[] {
  return Object.entries(INTERACTION_PROBLEM_CODES).map(
    ([name, entry]) => `| ${code(name)} | ${entry.status} | ${entry.description} |`
  );
}

