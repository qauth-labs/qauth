// Writes test-vectors/jwt/access-token.json: RFC 9068 §4 access token checks,
// each a pre-signed token with the JWKS and the clock to verify it against.
// Run by hand when a case is added (`node test-vectors/generators/access-token.mjs`);
// no test runs it, and the tests read the committed file.
//
// Deterministic: the throwaway Ed25519 keys come from fixed seeds and Ed25519
// signatures carry no randomness, so a re-run writes the same bytes. Only
// public keys go into the file.
import { execFileSync } from 'node:child_process';
import { createHash, createPrivateKey, createPublicKey, sign } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const OUT = 'test-vectors/jwt/access-token.json';

/** An Ed25519 key whose 32-byte seed is SHA-256 of a label that says it is a test key. */
function throwawayKey(label) {
  const seed = createHash('sha256').update(`qauth test-vectors throwaway ${label}`).digest();
  const pkcs8 = Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), seed]);
  const privateKey = createPrivateKey({ key: pkcs8, format: 'der', type: 'pkcs8' });
  return { privateKey, jwk: createPublicKey(privateKey).export({ format: 'jwk' }) };
}

const KID = 'throwaway-test-ed25519-1';
const signingKey = throwawayKey('ed25519 key 1');
const otherKey = throwawayKey('ed25519 key 2');
const JWKS = { keys: [{ ...signingKey.jwk, kid: KID, alg: 'EdDSA', use: 'sig' }] };

const NOW = 1767225600; // 2026-01-01T00:00:00Z
const ISSUER = 'https://as.example.com';
const AUDIENCE = 'https://rs.example.com';

const b64url = (value) => Buffer.from(JSON.stringify(value)).toString('base64url');

function jwt({ header = {}, claims = {}, key = signingKey } = {}) {
  const fullHeader = { alg: 'EdDSA', typ: 'at+jwt', kid: KID, ...header };
  const payload = {
    iss: ISSUER,
    sub: 'user-0001',
    aud: AUDIENCE,
    client_id: 'client-0001',
    scope: 'notes:read',
    iat: NOW - 60,
    exp: NOW + 840,
    jti: '0199f2b4-0000-7000-8000-000000000001',
    token_use: 'access',
    ...claims,
  };
  const input = `${b64url(fullHeader)}.${b64url(payload)}`;
  return {
    token: `${input}.${sign(null, Buffer.from(input), key.privateKey).toString('base64url')}`,
    payload,
  };
}

const good = jwt();
const cases = [
  {
    id: 'valid',
    token: good.token,
    expected: { valid: true, claims: good.payload },
    notes: 'Passes every check. claims is the whole verified payload.',
  },
  {
    id: 'wrong-issuer',
    token: jwt({ claims: { iss: 'https://other-as.example.com' } }).token,
    expected: { valid: false, reason: 'iss' },
    notes: 'RFC 9068 §4 step 3: iss must be the expected issuer.',
  },
  {
    id: 'wrong-audience',
    token: jwt({ claims: { aud: 'https://other-rs.example.com' } }).token,
    expected: { valid: false, reason: 'aud' },
    notes: 'RFC 9068 §4 step 4: aud must contain this resource server.',
  },
  {
    id: 'expired',
    token: jwt({ claims: { iat: NOW - 4500, exp: NOW - 3600 } }).token,
    expected: { valid: false, reason: 'exp' },
    notes: 'RFC 9068 §4 step 6: expired an hour before now.',
  },
  {
    id: 'wrong-typ',
    token: jwt({ header: { typ: 'JWT' } }).token,
    expected: { valid: false, reason: 'typ' },
    notes:
      'RFC 9068 §4 step 1: typ is JWT, the typ of a QAuth ID token signed with the same key, not at+jwt.',
  },
  {
    id: 'bad-signature',
    token: jwt({ key: otherKey }).token,
    expected: { valid: false, reason: 'signature' },
    notes:
      'RFC 9068 §4 step 5: signed by another key under the same kid, so the JWKS key does not verify it.',
  },
];

const file = {
  schema: 'qauth-vectors/1',
  id: 'jwt/access-token',
  description:
    'Access token checks a resource server runs on a QAuth JWT access token (RFC 9068 §4). input.token is a compact JWS signed with EdDSA (Ed25519). Select the key from input.jwks by the token header\'s kid, accept only EdDSA, and verify with input.now (Unix seconds) as the current time; the expected issuer is input.issuer and the expected audience is input.audience. Every case gives the same result with any clock tolerance from 0 to 60 seconds. expected.valid says whether the token passes; a valid token\'s expected.claims is its verified payload; an invalid token\'s expected.reason names the one check it fails: "typ" (the header typ is not at+jwt), "iss", "aud", "exp" or "signature". Each case is wrong in exactly one way. The JWKS holds a throwaway test key, generated from a fixed seed for this file.',
  source:
    'RFC 9068 §4 (validating JWT access tokens); generated by test-vectors/generators/access-token.mjs with Node.js node:crypto',
  cases: cases.map(({ id, token, expected, notes }) => ({
    id,
    input: { token, jwks: JWKS, now: NOW, issuer: ISSUER, audience: AUDIENCE },
    expected,
    notes,
  })),
};

writeFileSync(OUT, `${JSON.stringify(file, null, 2)}\n`);
execFileSync('pnpm', ['exec', 'prettier', '--write', '--log-level', 'warn', OUT], {
  stdio: 'inherit',
});
console.log(`wrote ${OUT} (${file.cases.length} cases)`);
